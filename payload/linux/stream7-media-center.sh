# Turns Debian 12 (i386) on the HP Stream 7 into a Kodi media center that
# boots straight into Kodi. Run as root on the tablet AFTER
# stream7-debian-postinstall.sh (firmware, zram and audio config come from there):
#
#   sudo sh stream7-media-center.sh                  # Kodi, landscape, auto-login
#   sudo sh stream7-media-center.sh --rotate left    # landscape the other way round
#   sudo sh stream7-media-center.sh --no-autologin   # pick Kodi at the login screen
#   sudo sh stream7-media-center.sh --user alice     # auto-login a specific user
#
# What it sets up:
#   - Kodi 20 + inputstream-adaptive, X11, lightdm
#   - i965-va-driver: Bay Trail VA-API, so H.264 / MPEG-2 / VC-1 decode in hardware
#     (HEVC/H.265 and VP9 have no hardware support on this chip - expect stutter)
#   - a "Lazarus7 Kodi" session: rotates the portrait 800x1280 panel to landscape,
#     maps the Goodix touchscreen to match, then runs kodi-standalone
# Safe to re-run. To go back: sudo rm /etc/lightdm/lightdm.conf.d/50-lazarus7-kodi.conf
set -eu

ROTATE=right
AUTOLOGIN=1
KODI_USER=""
while [ $# -gt 0 ]; do
    case "$1" in
        --rotate) ROTATE="${2:-right}"; shift 2 ;;
        --no-autologin) AUTOLOGIN=0; shift ;;
        --user) KODI_USER="${2:-}"; shift 2 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done
case "$ROTATE" in normal|left|right|inverted) ;; *) echo "--rotate must be normal, left, right or inverted" >&2; exit 2 ;; esac

echo "Lazarus7: for help only - use at your own risk, no warranty, no liability (DISCLAIMER.md)."
if [ "$(id -u)" -ne 0 ]; then
    echo "Run as root (sudo)." >&2
    exit 1
fi

if [ -z "$KODI_USER" ]; then
    KODI_USER="$(getent passwd 1000 | cut -d: -f1 || true)"
fi
if [ "$AUTOLOGIN" -eq 1 ] && [ -z "$KODI_USER" ]; then
    echo "No regular user (uid 1000) found; pass --user NAME or --no-autologin." >&2
    exit 1
fi

if ! grep -qs 'zram' /proc/swaps; then
    echo "Note: zram swap is not active. Run stream7-debian-postinstall.sh first - Kodi on 1 GB RAM needs it."
fi

apt-get update
apt-get install -y --no-install-recommends \
    xserver-xorg xserver-xorg-input-libinput x11-xserver-utils xinput \
    lightdm lightdm-gtk-greeter \
    kodi kodi-inputstream-adaptive \
    i965-va-driver vainfo alsa-utils

# Session wrapper: landscape + touch mapping, then Kodi.
cat > /usr/local/bin/lazarus7-kodi-session <<EOF
#!/bin/sh
# Generated by Lazarus7 stream7-media-center.sh
ROTATE="\${LAZARUS7_ROTATE:-$ROTATE}"
OUT="\$(xrandr --query | awk '/ connected/ {print \$1; exit}')"
if [ -n "\$OUT" ]; then
    xrandr --output "\$OUT" --rotate "\$ROTATE"
    # Keep touch lined up with the rotated picture.
    for id in \$(xinput list --id-only 2>/dev/null); do
        name="\$(xinput list --name-only "\$id" 2>/dev/null)"
        case "\$name" in
            *[Gg]oodix*|*[Tt]ouch*) xinput map-to-output "\$id" "\$OUT" 2>/dev/null || true ;;
        esac
    done
fi
export LIBVA_DRIVER_NAME=i965
exec kodi-standalone
EOF
chmod 755 /usr/local/bin/lazarus7-kodi-session

mkdir -p /usr/share/xsessions
cat > /usr/share/xsessions/lazarus7-kodi.desktop <<'EOF'
[Desktop Entry]
Name=Lazarus7 Kodi
Comment=Kodi media center, landscape, for the HP Stream 7
Exec=/usr/local/bin/lazarus7-kodi-session
Type=Application
EOF

mkdir -p /etc/lightdm/lightdm.conf.d
if [ "$AUTOLOGIN" -eq 1 ]; then
    cat > /etc/lightdm/lightdm.conf.d/50-lazarus7-kodi.conf <<EOF
[Seat:*]
autologin-user=$KODI_USER
autologin-user-timeout=0
autologin-session=lazarus7-kodi
user-session=lazarus7-kodi
EOF
    echo "Auto-login: $KODI_USER -> Kodi."
else
    rm -f /etc/lightdm/lightdm.conf.d/50-lazarus7-kodi.conf
    echo "No auto-login: choose \"Lazarus7 Kodi\" in the session menu of the login screen."
fi

systemctl enable lightdm >/dev/null 2>&1 || true

echo
echo "Done. Reboot to start Kodi:  sudo reboot"
echo "Hardware video decode check (after reboot, from a terminal):  vainfo"
echo "Picture upside down?  sudo sh $0 --rotate left"
echo "Touch: tap = select, swipe = scroll. A USB or Bluetooth keyboard/remote also works."
